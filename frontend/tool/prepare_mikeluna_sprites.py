"""Pack approved whole-body cels; never cut or transform individual body parts."""
from pathlib import Path
import json
import math
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'artwork/mikeluna'
spec = json.loads((ART / 'manifest.json').read_text())
size, cols, gutter = spec['cell_size'], spec['columns'], spec['gutter']
stride = size + gutter * 2
frames = spec['frames']
atlas = Image.new('RGBA', (cols * stride, math.ceil(len(frames) / cols) * stride))
sheet = Image.new('RGB', (cols * 220, math.ceil(len(frames) / cols) * 240), '#eaf6f5')
draw = ImageDraw.Draw(sheet)
for i, frame in enumerate(frames):
    cel = Image.open(ART / 'frames' / (frame['id'] + '.png')).convert('RGBA')
    assert cel.size == (size, size), frame['id']
    assert cel.getchannel('A').getextrema() == (0, 255), frame['id']
    x, y = i % cols, i // cols
    atlas.alpha_composite(cel, (x * stride + gutter, y * stride + gutter))
    thumb = cel.resize((220, 220), Image.Resampling.LANCZOS)
    sheet.paste(thumb, (x * 220, y * 240), thumb)
    draw.text((x * 220 + 8, y * 240 + 221), frame['id'], fill='#24535a')
asset = ROOT / 'assets/animations/mikeluna.webp'
atlas.save(asset, lossless=True, method=6)
sheet.save(ART / 'contact-sheet.jpg', quality=92)
keys = ',\n'.join('  ' + repr(f['id']) for f in frames)
(ROOT / 'lib/data/mikeluna_sprites.dart').write_text(
    '// Generated by tool/prepare_mikeluna_sprites.py.\n'
    "const mikelunaAtlasAsset = 'assets/animations/mikeluna.webp';\n"
    f'const mikelunaCellSize = {size};\n'
    f'const mikelunaAtlasColumns = {cols};\n'
    f'const mikelunaAtlasGutter = {gutter};\n'
    f'const mikelunaCelIds = <String>[\n{keys},\n];\n'
)
print(f'{len(frames)} cels, {atlas.width}x{atlas.height}, {asset.stat().st_size} bytes')
