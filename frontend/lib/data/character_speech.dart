/// 旧保存データや不明なIDは、画像と同じルールでキャラを解決します。
List<String> speechLinesFor(String kind) =>
    characterSpeechLines[characterForm(kind).imageId]!;

/// 直前のセリフを除いた候補から、均等にランダムで選びます。
String pickCharacterSpeech(
  String kind, {
  required Random random,
  String? previous,
}) {
  final lines = speechLinesFor(kind);
  final candidates = lines.where((line) => line != previous).toList();
  return candidates[random.nextInt(candidates.length)];
}
